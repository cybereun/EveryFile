export const productTranslations: Record<Locale, { tagline: string }> = {
  ko: { tagline: "파일을 찾는 가장 빠른 방법" },
  en: { tagline: english["파일을 찾는 가장 빠른 방법"] },
};

export type Translator = (source: string, values?: Record<string, string | number>) => string;

export function createTranslator(locale: Locale): Translator {
  return (source, values) => {
    const translated = locale === "en" ? english[source] ?? source : source;
    if (!values) return translated;
    return Object.entries(values).reduce(
      (result, [key, value]) => result.split(`{${key}}`).join(String(value)),
      translated,
    );
  };
}

interface I18nContextValue {
  locale: Locale;
  t: Translator;
}

const defaultContext: I18nContextValue = {
  locale: defaultLocale,
  t: createTranslator(defaultLocale),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  const value = useMemo(() => ({ locale, t: createTranslator(locale) }), [locale]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  return useContext(I18nContext);
}
